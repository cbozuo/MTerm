"""Re-vendor the IronRDP family from a pristine upstream checkout.

    python scripts/vendor-ironrdp.py <path-to-IronRDP-checkout>

Why vendored instead of depended on: the released `ironrdp` facade (0.17.0)
predates `ActiveStage::reactivate`. The released session keeps the bulk
decompressor *inside* the fast-path processor, so the reactivation that follows
a desktop resize rebuilds the processor and drops the decompression history —
while the server keeps streaming against it, which decodes into the corrupt
patches a resize flashes. Upstream master moved the decompressor out of the
processor (owned by the stage, passed per update) and added `reactivate`.

What this script does, and why each step exists:

* copies only the crates reachable from `ironrdp` + `ironrdp-client` by *path*
  dependencies (a superset: optional edges included, dev-dependencies excluded,
  because a dependency's dev-deps are never activated). Copying the whole
  upstream workspace would be ~83 crates / 26 MB of which most is never built.
* keeps the upstream workspace root manifest, because ~all member manifests
  inherit `[workspace.package]` / `[workspace.dependencies]` / `[workspace.lints]`
  from it (flattening 60 manifests by hand is how you get a subtle mistake).
  It narrows `members` to the crates actually copied and drops the `[profile.*]`
  sections — cargo ignores a non-root workspace's profiles and warns about them.
* deliberately does NOT copy the upstream `rust-toolchain.toml` or `.cargo/`:
  both would leak upstream build settings into this repository.
"""

import os
import shutil
import sys

DEST = os.path.join("vendor", "ironrdp")
ROOTS = ["ironrdp", "ironrdp-client"]
SKIP = (".git", "target", "Cargo.lock")


def read_manifest(path):
    try:
        import tomllib
    except ModuleNotFoundError:  # Python < 3.11
        raise SystemExit("!! needs Python 3.11+ (tomllib); found %s" % sys.version)
    with open(path, "rb") as handle:
        return tomllib.load(handle)


def dependency_closure(upstream):
    """Crate directories reachable from the roots by path dependencies."""
    crates = os.path.join(upstream, "crates")
    by_name, deps = {}, {}
    for entry in sorted(os.listdir(crates)):
        manifest = os.path.join(crates, entry, "Cargo.toml")
        if not os.path.isfile(manifest):
            continue
        table = read_manifest(manifest)
        name = table.get("package", {}).get("name")
        if not name:
            continue
        by_name[name] = entry
        found = set()

        def collect(section):
            for key, value in (section or {}).items():
                if isinstance(value, dict) and "path" in value:
                    found.add(key)

        for key in ("dependencies", "build-dependencies"):
            collect(table.get(key))
        for per_target in (table.get("target") or {}).values():
            for key in ("dependencies", "build-dependencies"):
                collect(per_target.get(key))
        deps[name] = found

    seen, todo = set(), list(ROOTS)
    while todo:
        name = todo.pop()
        if name in seen or name not in by_name:
            continue
        seen.add(name)
        todo.extend(dep for dep in deps.get(name, ()) if dep not in seen)
    return sorted(by_name[name] for name in seen if name in by_name)


def workspace_root(upstream, commit):
    source = open(os.path.join(upstream, "Cargo.toml"), encoding="utf-8").read()
    head, workspace = source[: source.index("[workspace]")], source[source.index("[workspace]") :]
    start = workspace.index("members = [")
    end = workspace.index("]", start) + 1
    workspace = workspace[:start] + 'members = ["crates/*"]' + workspace[end:]
    profiles = workspace.find("\n[profile.")
    if profiles != -1:
        workspace = workspace[:profiles] + "\n"
    banner = f"""# Vendored IronRDP workspace (MTerm) - regenerated by scripts/vendor-ironrdp.py.
#
# Source: https://github.com/Devolutions/IronRDP at {commit}.
#
# Do not edit by hand: run the script against a checkout at the wanted commit.
# Only the crates reachable from `ironrdp` and `ironrdp-client` are present, so
# `members` is narrowed to that subset; the upstream `[profile.*]` sections are
# dropped (cargo ignores a non-root workspace's profiles and says so). The
# upstream `rust-toolchain.toml` and `.cargo/` are not copied on purpose.
"""
    return banner + head + workspace


def apply_local_patches():
    """Re-apply MTerm's own hunks to the vendored sources.

    Kept as explicit string surgery (not a .patch file) so a re-sync fails loudly
    when upstream moves the code, instead of silently applying to the wrong
    place. Currently one patch:

    `#rdp-frame-copies` — `RdpOutputEvent::Image` carries the decoded RGBA bytes
    instead of pixels packed into `u32`. Upstream's packing costs a full-image
    pass per frame *and* zeroes the alpha byte, and this embedder reads alpha as
    "the decoder has painted this pixel" (see the hole compositing in
    src/rdp/embedded/impls/client.rs) — with upstream's packing a freshly
    reactivated framebuffer would look fully painted and the desktop would stop
    updating until the server repainted it.
    """
    path = os.path.join(DEST, "crates", "ironrdp-client", "src", "rdp.rs")
    with open(path, encoding="utf-8") as handle:
        source = handle.read()

    field = """    Image {
        buffer: Vec<u32>,
        width: NonZeroU16,
        height: NonZeroU16,
    },
"""
    field_patched = """    Image {
        /// The frame's pixels, RGBA, four bytes per pixel, row by row.
        ///
        /// (MTerm patch, `#rdp-frame-copies`) Upstream packs every pixel into a
        /// `u32` here, which costs a full-image pass per frame and drops the
        /// alpha byte — and this client keeps alpha meaningful: a pixel the
        /// decoder has not painted yet is already `0x00` after a (re)activation,
        /// which is how the embedder tells a hole from a black desktop. Taking
        /// the decoded buffer as it is costs neither.
        buffer: Vec<u8>,
        width: NonZeroU16,
        height: NonZeroU16,
    },
"""
    if field_patched not in source:
        if field not in source:
            raise SystemExit("!! #rdp-frame-copies: the Image variant has moved")
        source = source.replace(field, field_patched, 1)

    pack = """                    let buffer = pack_desktop_update(
                        &image,
                        width,
                        height,
                        InclusiveRectangle {
                            left: 0,
                            top: 0,
                            right: width.get() - 1,
                            bottom: height.get() - 1,
                        },
                    )?
                    .buffer;
"""
    pack_patched = """                    // (MTerm patch, `#rdp-frame-copies`) Hand over the decoded
                    // RGBA bytes as they are: the packing into `u32` below is a
                    // full-image pass that also drops the alpha byte this client
                    // uses to tell a not-yet-painted pixel from a black one.
                    let buffer = image.data().to_vec();
"""
    if pack_patched not in source:
        if pack not in source:
            raise SystemExit("!! #rdp-frame-copies: the full-frame packing site has moved")
        source = source.replace(pack, pack_patched, 1)

    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(source)

    # The latest-only slot mirrors the same payload, so it moves with it.
    channel = os.path.join(DEST, "crates", "ironrdp-client", "src", "output_channel.rs")
    with open(channel, encoding="utf-8") as handle:
        slot = handle.read()
    slot_field = """    Image {
        buffer: Vec<u32>,
        width: NonZeroU16,
        height: NonZeroU16,
    },
"""
    slot_patched = """    Image {
        // (MTerm patch, `#rdp-frame-copies`) Matches `RdpOutputEvent::Image`:
        // the frame travels as decoded RGBA bytes, not packed `u32` pixels.
        buffer: Vec<u8>,
        width: NonZeroU16,
        height: NonZeroU16,
    },
"""
    if slot_patched not in slot:
        if slot_field not in slot:
            raise SystemExit("!! #rdp-frame-copies: LatestPayload::Image has moved")
        slot = slot.replace(slot_field, slot_patched, 1)
        with open(channel, "w", encoding="utf-8", newline="") as handle:
            handle.write(slot)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    upstream = os.path.abspath(sys.argv[1])
    if not os.path.isdir(os.path.join(upstream, "crates")):
        raise SystemExit("!! %s does not look like an IronRDP checkout" % upstream)
    commit = os.popen(f'git -C "{upstream}" rev-parse HEAD').read().strip() or "unknown"

    dirs = dependency_closure(upstream)
    os.makedirs(os.path.join(DEST, "crates"), exist_ok=True)
    for entry in dirs:
        target = os.path.join(DEST, "crates", entry)
        shutil.rmtree(target, ignore_errors=True)
        shutil.copytree(
            os.path.join(upstream, "crates", entry),
            target,
            ignore=shutil.ignore_patterns(*SKIP),
        )
    with open(os.path.join(DEST, "Cargo.toml"), "w", encoding="utf-8", newline="") as handle:
        handle.write(workspace_root(upstream, commit))

    apply_local_patches()

    rust = sum(
        1
        for _root, _dirs, files in os.walk(os.path.join(DEST, "crates"))
        for name in files
        if name.endswith(".rs")
    )
    print("vendored %d crates (%d .rs) from %s" % (len(dirs), rust, commit))


if __name__ == "__main__":
    main()
